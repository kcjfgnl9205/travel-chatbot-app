-- 관광지 사진의 출처를 같이 남긴다 (0010 다음. 재실행해도 안전하다)
--
-- 위키미디어 자동 탐색을 되살리면서 **저작자 표시 문제를 같이 푼다.**
--
-- 0009 가 그 탐색을 걷어낸 이유 중 하나가 이것이었다 — 위키미디어 사진은 대부분
-- 저작자 표시가 필요한 라이선스(CC BY-SA 등)인데, 우리는 사진 주소만 받아오고
-- **어디서 온 것인지조차 저장하지 않았다.** 밝히고 싶어도 밝힐 수가 없었다.
--
-- 이제 사진을 찾은 문서의 주소를 같이 남긴다. 저작자와 라이선스는 그 문서에 있으므로,
-- 관리 화면과 (필요해지면) 카드 하단에서 그 링크로 출처를 밝힐 수 있다.
--
-- ⚠️ **사람이 직접 넣은 사진에는 이 값이 없을 수 있다.** 그건 정상이다 — 출처를
--    아는 사람이 넣은 것이고, 위키미디어가 아닐 수도 있다.
alter table public.attractions
    add column if not exists image_source text,
    add column if not exists name_en      text;

comment on column public.attractions.image_source is
    '사진을 찾은 문서 주소 (위키백과·위키미디어 커먼즈). 저작자와 라이선스가 거기 있다. '
    '⚠️ 위키미디어 사진은 대부분 저작자 표시가 필요하다 — 이 값이 그걸 밝힐 유일한 단서다. '
    '사람이 직접 넣은 사진은 비어 있을 수 있다.';

comment on column public.attractions.name_en is
    '영문·현지 공식명 (Osaka Castle). **카드에는 안 쓴다 — 사진을 찾는 데만 쓴다.** '
    '위키미디어 커먼즈의 파일명은 거의 영문이라, 이 값이 없으면 한국어로 뒤지게 되고 '
    '그러면 거의 못 찾는다. 후쿠오카 실측: 영문명 없이 4/14, 있으면 11/14.';
